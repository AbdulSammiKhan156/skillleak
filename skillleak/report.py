"""Markdown exports for the gap report and generated labs."""
from __future__ import annotations

from .prompts import BLOOM
from .scoring import score_run, coverage_index, is_verified


def lab_markdown(lab: dict) -> str:
    L = []
    L.append(f"# {lab.get('title', 'Practical Lab')}")
    L.append(f"**Target competency:** {lab.get('target_competency', '')}  ")
    L.append(f"**Bloom target:** {lab.get('bloom_target', '')}  ")
    L.append(f"**Duration:** {lab.get('duration_minutes', '')} minutes  ")
    L.append(f"**Tools:** {', '.join(lab.get('tools', []))}")
    L.append(f"\n**Learning outcome:** {lab.get('learning_outcome', '')}")
    L.append(f"\n## Scenario\n{lab.get('scenario', '')}")
    if lab.get("instructor_setup"):
        L.append("\n## Instructor setup")
        L += [f"- {s}" for s in lab["instructor_setup"]]
    L.append("\n## Student tasks")
    L += [f"{i}. {s}" for i, s in enumerate(lab.get("student_tasks", []), 1)]
    L.append("\n## Evidence to submit")
    L += [f"- {s}" for s in lab.get("evidence_to_submit", [])]
    L.append("\n## Marking rubric\n")
    L.append("| Criterion | Points | Excellent | Satisfactory | Needs improvement |")
    L.append("|---|---|---|---|---|")
    for r in lab.get("rubric", []):
        L.append(f"| {r.get('criterion','')} | {r.get('points','')} | {r.get('excellent','')} | "
                 f"{r.get('satisfactory','')} | {r.get('needs_improvement','')} |")
    L.append(f"\n## How this closes the gap\n{lab.get('how_it_closes_gap', '')}")
    if lab.get("assessment_variant"):
        L.append(f"\n## Matching assessment question\n{lab['assessment_variant']}")
    rv = lab.get("review", {})
    L.append(f"\n---\nTeacher review: **{rv.get('status', 'Pending review')}**"
             + (f" - {rv['note']}" if rv.get("note") else ""))
    L.append(f"\n_Generated by SkillLeak AI ({lab.get('_meta', {}).get('model', '')}). "
             "AI-drafted content - must be reviewed by an instructor before use._")
    return "\n".join(L)


def run_markdown(run: dict) -> str:
    rows = score_run(run)
    comps = {c["id"]: c for c in run["competencies"]}
    names = {d["doc_id"]: d["name"] for d in run["documents"]}
    L = ["# SkillLeak AI - Curriculum Evidence Report", ""]
    if run.get("alignment"):
        L.append("_The CLO alignment section is exported separately from the CLO Alignment tab._")
    if not run.get("competencies"):
        L.append("\nNo industry skill-gap analysis in this scan.")
        return "\n".join(L)
    L.append(f"- Job family analysed: **{run.get('job_family', '')}**")
    L.append(f"- Scan time: {run['meta']['created_at']}  |  Model: {run['meta']['model']}")
    L.append(f"- Demand-weighted evidence coverage: **{coverage_index(rows):.0f}%** (prototype indicator)")
    L.append(f"- AI quotes rejected by source verification: {run['meta']['quotes_rejected']} "
             f"of {run['meta']['quotes_total']}")
    L.append("\nDocuments: " + ", ".join(f"{k} = {v}" for k, v in names.items()))
    L.append("\n## Priority table\n")
    L.append("Gap priority = D x (3 - (T + P + A)). P and A require Bloom level Apply (3) or higher.\n")
    L.append("| # | Competency | Status | D | T | P | A | Priority |")
    L.append("|---|---|---|---|---|---|---|---|")
    for i, r in enumerate(rows, 1):
        L.append(f"| {i} | {r['name']} | {r['status']} | {r['D']} | {r['T']} | {r['P']} | {r['A']} | {r['priority']} |")
    L.append("\n## Findings with evidence\n")
    for r in rows:
        c = comps[r["id"]]
        L.append(f"### {r['name']}  ({r['status']}, priority {r['priority']})")
        L.append(f"{r['diagnosis']}\n")
        for e in c["industry_evidence"]:
            if is_verified(e):
                L.append(f"- Employer ({names.get(e['doc_id'], e['doc_id'])}): \"{e['quote']}\"")
        for e in c["course_evidence"]:
            if is_verified(e):
                L.append(f"- Course {e['category']} ({names.get(e['doc_id'], e['doc_id'])}, "
                         f"Bloom: {BLOOM.get(e['bloom_level'])}): \"{e['quote']}\"")
        L.append("")
    if run.get("labs"):
        L.append("\n## Proposed interventions\n")
        for cid, lab in run["labs"].items():
            L.append(lab_markdown(lab))
            L.append("")
    L.append("\n---\n_Limitations: findings reflect only the documents supplied. Missing evidence is a "
             "signal to investigate, not proof that a skill is not taught or that students lack it. "
             "Educators must validate all findings._")
    return "\n".join(L)


def alignment_markdown(run: dict) -> str:
    from .clo import analyze, level_name
    al = run.get("alignment")
    if not al:
        return "# SkillLeak AI - CLO alignment\n\nNo CLO alignment analysis in this scan."
    res = analyze(al)
    sm = res["summary"]
    L = ["# SkillLeak AI - CLO-Assessment Alignment Report", ""]
    L.append("_Decision support for faculty review. Not an official PEC or accreditation judgement._\n")
    if al.get("course"):
        L.append(f"- Course: **{al['course']}**")
    L.append(f"- Scan: {run['meta']['created_at']} | Model: {run['meta']['model']}")
    L.append(f"- CLOs detected: {sm['clos']} | with assessment evidence: {sm['with_evidence']} | "
             f"potential mismatches: {sm['mismatch']} | insufficient evidence: {sm['insufficient']} | "
             f"needs review: {sm['review']}")
    L.append(f"- Alignment indicator: {sm['aligned']}/{sm['clos']} CLOs with no apparent mismatch "
             "(prototype heuristic)\n")
    L.append("| CLO | Statement | Intended level | Highest item demand | Items at level | Finding |")
    L.append("|---|---|---|---|---|---|")
    for r in res["rows"]:
        L.append(f"| {r['id']} | {r['statement']} | {level_name(r['target'])} ({r['target_src']}) | "
                 f"{level_name(r['max_demand']) if r['max_demand'] else '-'} | {r['n_at_level']}/{r['n_items']} | "
                 f"{r['finding']} |")
    L.append("\n## Findings\n")
    for r in res["rows"]:
        L.append(f"### {r['id']} - {r['finding']}")
        L.append(f"{r['explanation']}  \n**Suggested action:** {r['action']}\n")
        for m in res["mapping_rows"]:
            if m["clo_id"] == r["id"]:
                flag = "" if m["included"] else " (excluded)"
                L.append(f"- {m['item_label']}{flag}: demand {level_name(m['demand'])}, marks "
                         f"{m['marks'] if m['marks'] is not None else 'n/a'}, {m['basis'].replace('_', ' ')} - "
                         f"\"{m['quote']}\"")
        imp = al.get("improvements", {}).get(r["id"])
        if imp:
            L.append(f"\n**Proposed item (AI draft, level C{imp.get('bloom_level')}):** {imp.get('revised_item', '')}")
        L.append("")
    if res["unmapped_items"]:
        L.append("## Assessment items not mapped to any CLO")
        L += [f"- {i['label']}: \"{i['quote']}\"" for i in res["unmapped_items"]]
    if al.get("missing_information"):
        L.append("\n## Missing information reported")
        L += [f"- {x}" for x in al["missing_information"]]
    return "\n".join(L)


def student_markdown(p: dict) -> str:
    L = [f"# Practice plan: {p.get('skill', '')}", "", f"**Why it matters:** {p.get('why_it_matters', '')}", ""]
    L.append(f"## {p.get('exercise_title', 'Exercise')}")
    L.append(f"Time: {p.get('time_needed', '')} | Tools: {', '.join(map(str, p.get('tools', [])))}\n")
    L += [f"{i}. {s}" for i, s in enumerate(p.get("steps", []), 1)]
    L.append("\n## Expected output")
    L += [f"- {s}" for s in p.get("expected_output", [])]
    L.append("\n## Self-check")
    L += [f"- [ ] {s}" for s in p.get("self_check", [])]
    L.append("\n## Next steps")
    L += [f"- {s}" for s in p.get("next_steps", [])]
    L.append("\n_Generated by SkillLeak AI. AI-generated study plan._")
    return "\n".join(L)
