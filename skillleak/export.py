"""Course-file pack: one Excel workbook a faculty member / OBE coordinator can file or edit."""
from __future__ import annotations

import io

import pandas as pd

from .clo import analyze, level_name, level_range
from .scoring import score_run, is_verified


def _autosize(ws, df: pd.DataFrame) -> None:
    from openpyxl.styles import Alignment, Font, PatternFill
    for i, col in enumerate(df.columns, start=1):
        width = min(60, max(10, int(df[col].astype(str).str.len().max() if len(df) else 10), len(str(col))) + 2)
        ws.column_dimensions[ws.cell(row=1, column=i).column_letter].width = width
        c = ws.cell(row=1, column=i)
        c.font = Font(bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor="184F95")
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.alignment = Alignment(wrap_text=True, vertical="top")
    ws.freeze_panes = "A2"


def course_file_pack(run: dict, attainment_rows: list[dict] | None = None,
                     plo_rows: list[dict] | None = None, sources: list[dict] | None = None) -> bytes:
    sheets: dict[str, pd.DataFrame] = {}
    meta = run.get("meta", {})
    sheets["About"] = pd.DataFrame([
        {"Field": "Generated by", "Value": "SkillLeak AI - decision support for faculty review"},
        {"Field": "Important", "Value": "Findings are potential issues for review, not official PEC/HEC or "
                                       "accreditation judgements."},
        {"Field": "Scan time", "Value": meta.get("created_at", "")},
        {"Field": "Model", "Value": meta.get("model", "")},
        {"Field": "Input", "Value": meta.get("input", "")},
    ])
    al = run.get("alignment")
    if al:
        res = analyze(al)
        sheets["CLO Alignment"] = pd.DataFrame([{
            "CLO": r["id"], "Statement": r["statement"], "PLO": r["plo"],
            "Intended level": level_name(r["target"]), "Level source": r["target_src"],
            "Highest item demand": level_name(r["max_demand"]) if r["max_demand"] else "",
            "Items at level / mapped": f"{r['n_at_level']}/{r['n_items']}",
            "Aligned-mark share": (f"{r['marks_share_at_level']:.0%}" if r["marks_share_at_level"] is not None else ""),
            "Finding": r["finding"], "Severity": r.get("severity", ""),
            "Reason": r["explanation"], "Suggested action": r["action"],
        } for r in res["rows"]])
        items = [i for i in al["items"] if is_verified(i)]
        clos = [c["id"] for c in al["clos"]]
        matrix = []
        for it in items:
            row = {"Item": it["label"], "Marks": it["marks"], "Text": it["quote"],
                   "AI demand (rater 1)": level_name(it.get("demand_level")),
                   "AI demand (rater 2)": level_name(it.get("demand_level_2")) if it.get("demand_level_2") else ""}
            for c in clos:
                row[c] = ""
            for m in res["mapping_rows"]:
                if m["item_id"] == it["id"] and m["clo_id"] in row:
                    row[m["clo_id"]] = ("X" if m["basis"] == "explicit_tag" else "x (AI)") + \
                                       ("" if m["included"] else " excluded")
            matrix.append(row)
        sheets["CLO x Item Matrix"] = pd.DataFrame(matrix)
        if al.get("improvements"):
            sheets["Proposed Items"] = pd.DataFrame([{
                "CLO": k, "Proposed item": v.get("revised_item", ""), "Type": v.get("item_type", ""),
                "Marks": v.get("marks", ""), "AI-estimated level": level_name(v.get("bloom_level")),
                "Why": v.get("why_it_measures_the_clo", ""), "Status": "AI draft - faculty to review",
            } for k, v in al["improvements"].items()])
    if attainment_rows:
        sheets["CLO Attainment"] = pd.DataFrame([{
            "CLO": a["clo"], "Questions": ", ".join(a["questions"]), "Max marks": a["max_marks"],
            "Students": a["n_students"], "Average score": f"{a['avg_score']:.0%}",
            "Class attainment": f"{a['class_attainment']:.0%}", "Attained": "Yes" if a["attained"] else "No",
            "Intended level": level_name(a.get("intended")), "Measured up to": level_name(a.get("measured_up_to")),
            "Validity flag": a.get("flag", ""), "Note": a.get("note", ""),
        } for a in attainment_rows])
    if plo_rows:
        sheets["PLO Evidence Coverage"] = pd.DataFrame([{
            "PLO": p["plo_label"], "CLOs": ", ".join(p["clos"]),
            "Highest intended": level_name(p["highest_intended"]),
            "Highest evidenced": level_name(p["highest_evidenced"]),
            "Weak CLOs": ", ".join(p["weak_clos"]), "Evidence": p["evidence"],
            "Average attainment": f"{p['avg_attainment']:.0%}" if p["avg_attainment"] is not None else "",
        } for p in plo_rows])
    if run.get("competencies"):
        sheets["Industry Gaps"] = pd.DataFrame([{
            "Competency": r["name"], "Postings": r["jd_count"], "D": r["D"], "T": r["T"], "P": r["P"],
            "A": r["A"], "Priority": r["priority"], "Status": r["status"], "Diagnosis": r["diagnosis"],
        } for r in score_run(run)])
    if sources:
        sheets["Job Sources"] = pd.DataFrame(sources)
    buf = io.BytesIO()
    with pd.ExcelWriter(buf, engine="openpyxl") as xw:
        for name, df in sheets.items():
            df.to_excel(xw, sheet_name=name[:31], index=False)
            _autosize(xw.sheets[name[:31]], df)
    return buf.getvalue()


__all__ = ["course_file_pack", "level_range"]
